// Package agentcli provides a framework for building agent-friendly CLIs using
// Cobra. It enforces the three commands every agent CLI must expose:
//
//   - completions – shell tab-completion scripts
//   - skill       – machine-readable description of what the CLI can do
//   - logs        – streaming log output with agent-friendly options
//
// It also adds the global --json, --yaml, and --yml flags.
//
// Typical usage:
//
//	root := agentcli.New(agentcli.Config{
//	    Use:         "mycli",
//	    Short:       "My agent-friendly CLI",
//	    SkillSource: "SKILL.md",
//	    LogSource:   func() (io.Reader, error) { ... },
//	})
//	root.AddCommand(myCustomCmd)
//	root.Execute()
package agentcli

import (
	"fmt"
	"os"

	"github.com/spf13/cobra"
)

// RootOptions holds the global flag values shared across all commands.
type RootOptions struct {
	OutputJSON bool
	OutputYAML bool
	OutputYML  bool
}

// Config is the configuration passed to New when creating a root command.
type Config struct {
	// Use is the one-line usage string for the CLI (e.g. "mycli").
	Use string
	// Short is a one-line description shown in help output.
	Short string
	// Long is the full description shown in the help for the root command.
	Long string
	// Version is the version string (e.g. "1.2.3").
	Version string

	// SkillSource is the path to a SKILL.md (or similar) file whose content is
	// included verbatim in the skill command output. If empty, only the
	// generated command-tree description is shown.
	SkillSource string

	// LogProvider is called by the logs command to open the log stream.
	// It receives the flags specified by the caller and should return an open
	// reader that streams log lines, plus an optional cleanup function.
	// If nil the logs command will print an informational message asking the
	// integrating CLI to register a provider via RegisterLogProvider.
	LogProvider LogProviderFunc
}

// optsKey is the context key used to store *RootOptions on a cobra.Command.
const optsKey = "__agentcli_opts__"

// New creates a fully-configured Cobra root command for an agent CLI.
// The returned command already has the completions, skill, and logs sub-commands
// attached along with the required global flags.
func New(cfg Config) *cobra.Command {
	opts := &RootOptions{}

	root := &cobra.Command{
		Use:           cfg.Use,
		Short:         cfg.Short,
		Long:          cfg.Long,
		Version:       cfg.Version,
		SilenceUsage:  true,
		SilenceErrors: true,
		PersistentPreRunE: func(cmd *cobra.Command, _ []string) error {
			return opts.ValidateOutputFlags()
		},
	}

	// Store the options pointer in Annotations so sub-commands can retrieve it
	// via Opts(cmd).
	root.Annotations = map[string]string{optsKey: ""}
	// We embed the pointer as a side-channel via the command itself by keeping
	// a mapping from command pointer to options.
	registerOpts(root, opts)

	// Register global output flags.
	root.PersistentFlags().BoolVar(&opts.OutputJSON, "json", false, "Output machine-readable JSON")
	root.PersistentFlags().BoolVar(&opts.OutputYAML, "yaml", false, "Output machine-readable YAML")
	root.PersistentFlags().BoolVar(&opts.OutputYML, "yml", false, "Alias for --yaml")

	// Disable the default 'completion' command generated by Cobra; we provide
	// our own 'completions' (plural) command instead.
	root.CompletionOptions.DisableDefaultCmd = true

	// Attach the required commands.
	root.AddCommand(newCompletionCmd(root, opts))
	root.AddCommand(newSkillCmd(root, opts, cfg))
	root.AddCommand(newLogsCmd(opts, cfg))

	return root
}

// optsRegistry maps a *cobra.Command root to its *RootOptions.
var optsRegistry = map[*cobra.Command]*RootOptions{}

func registerOpts(root *cobra.Command, opts *RootOptions) {
	optsRegistry[root] = opts
}

// Opts returns the RootOptions for the root command that cmd belongs to.
// This lets sub-commands respect the global --json / --yaml flags.
// It returns an empty (text-mode) RootOptions if none is found.
func Opts(cmd *cobra.Command) *RootOptions {
	root := cmd.Root()
	if o, ok := optsRegistry[root]; ok {
		return o
	}
	return &RootOptions{}
}

// Execute is a convenience wrapper that runs the root command and exits with
// status 1 on error.
func Execute(root *cobra.Command) {
	if err := root.Execute(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// RequiredCommands returns the names of the commands that every agent CLI must
// expose. Use this list to validate an existing cobra.Command tree.
func RequiredCommands() []string {
	return []string{"completions", "skill", "logs"}
}

// ValidateRequiredCommands checks that all required commands are present in the
// given root command and returns an error listing any that are missing.
func ValidateRequiredCommands(root *cobra.Command) error {
	required := RequiredCommands()
	present := make(map[string]bool, len(root.Commands()))
	for _, cmd := range root.Commands() {
		present[cmd.Name()] = true
	}
	var missing []string
	for _, name := range required {
		if !present[name] {
			missing = append(missing, name)
		}
	}
	if len(missing) == 0 {
		return nil
	}
	return fmt.Errorf("agent CLI is missing required commands: %v", missing)
}
